def map_gt(gt):
    """gt: (H,W) 的 raw id 数组 -> (H,W) 的 0-based nyu40id，未知/未标注记 -1。"""
    gt = np.asarray(gt, dtype=np.int64)
    out = np.full(gt.shape, -1, dtype=np.int16)
    keys = np.fromiter(RAW2NYU.keys(), dtype=np.int64, count=len(RAW2NYU))
    vals = np.fromiter(RAW2NYU.values(), dtype=np.int16, count=len(RAW2NYU))
    # 用 searchsorted 向量化查表（raw id 是稀疏正整数）
    order = np.argsort(keys)
    ks = keys[order]; vs = vals[order]
    pos = np.searchsorted(ks, gt)
    pos = np.clip(pos, 0, len(ks) - 1)
    hit = ks[pos] == gt
    out[hit] = vs[pos][hit]
    return out
